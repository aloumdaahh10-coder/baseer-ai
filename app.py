if st.button("فحص وتدقيق من فتاوى ابن باز", type="primary"):
    if not query.strip():
        st.warning("يرجى كتابة نص أو مسألة أولاً لإجراء الفحص والتدقيق.")
    else:
        best_match = None
        highest_score = 0

        # فحص التطابق اللغوي والدلالي الصارم
        for fatwa in BINBAZ_FATWAS:
            score_title = fuzz.partial_ratio(query, fatwa["title"])
            max_kw = max([fuzz.partial_ratio(query, kw) for kw in fatwa["keywords"]])
            score = max(score_title, max_kw)

            if score > highest_score:
                highest_score = score
                best_match = fatwa

        # الحالة 1: ثبوت النص وتجاوز عتبة الثقة (ظهور بطاقة الموثوقية)
        if highest_score >= 60:
            st.success("✅ نتيجة الفحص: تم العثور على الفتوى المعتمدة في أرشيف الموقع الرسمي")
            with st.container(border=True):
                st.subheader("📋 بطاقة الموثوقية الشرعية (Reliability Badge)")
                st.markdown(f"**عنوان الفتوى:** {best_match['title']}")
                st.write(f"**خلاصة جواب الشيخ:** {best_match['snippet']}")
                st.write(f"**مؤشر الثقة والمطابقة:** `{highest_score}%` (استرجاع إسنادي مقيد)")
                st.markdown(f"🔗 **رابط المصدر:** [الانتقال للفتوى في الموقع الرسمي للشيخ]({best_match['url']})")
                st.caption("المصدر المعتمد: مؤسسة الشيخ عبدالعزيز بن باز الخيرية - binbaz.org.sa")

        # الحالة 2: غياب السند أو تدني الثقة (تفعيل الامتناع والإحالة الآلية - صفر هلوسة)
        else:
            st.error("⚠️ تنبيه: تعذر إثبات المسألة في فتاوى الموقع المعتمدة")
            with st.container(border=True):
                st.subheader("⛔ تفعيل خوارزمية الامتناع الآلي (Zero-Hallucination Guard)")
                st.markdown("""
                - **حالة البحث:** لم نجد نصاً مباشراً يطابق هذه المسألة في الأرشيف المعتمد حالياً.
                - **إجراء النظام:** امتنع المحرك آلياً عن تلفيق أي فتوى صيانةً للأمانة العلمية وشرط الموثوقية.
                - **الإحالة:** تمت إحالة المسألة للجنة الدائمة للبحوث العلمية والإفتاء أو للمختص الشرعي.
                """)
                st.info("💡 مبدأ السلامة العلمية: التوقف عند عدم العثور على المرجع خيرٌ من الهلوسة وتلفيق الأحكام الشرعية.")
